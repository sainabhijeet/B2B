export function IndustryIcon({ name, className }: { name: string; className?: string }) {
  const Icon = MAP[name] ?? Box;
  return <Icon className={className ?? 'h-4 w-4 shrink-0 text-slate-600'} aria-hidden />;
}

export function getIndustryIconComponent(name: string): ComponentType<LucideProps> {
  return MAP[name] ?? Box;
}
